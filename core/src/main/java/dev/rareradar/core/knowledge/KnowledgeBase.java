        private void tagsArray(JsonReader r, String file) throws IOException {
            r.beginArray();
            while (r.hasNext()) {
                JsonObject o = JsonParser.parseReader(r).getAsJsonObject();
                List<BiomeTag.Value> values = new ArrayList<>();
                if (o.get("values") instanceof JsonArray a)
                    for (JsonElement e : a) {
                        JsonObject v = e.getAsJsonObject();
                        String ref = s(v, "id");
                        if (ref != null) values.add(new BiomeTag.Value(ref, !Boolean.FALSE.equals(bool(v, "required"))));
                    }
                BiomeTag t = new BiomeTag(s(o, "id"), bool(o, "replace"), List.copyOf(values), s(o, "sourceFile"));
                if (t.id() == null) throw new IllegalStateException("biome tag without id");
                tags.put(t.id(), t);
            }
            r.endArray();
        }

        // ------------------------------------------------------------ JSON helpers

        private String intern(String v) {
            if (v == null) return null;
            String prev = pool.putIfAbsent(v, v);
            return prev == null ? v : prev;
        }

        private String s(JsonObject o, String k) { return intern(str(o, k)); }

        private static String str(JsonObject o, String k) {
            JsonElement e = o.get(k);
            return e == null || e.isJsonNull() || !e.isJsonPrimitive() ? null : e.getAsString();
        }

        private static Integer integer(JsonObject o, String k) {
            JsonElement e = o.get(k);
            return e == null || e.isJsonNull() || !e.isJsonPrimitive() ? null : e.getAsInt();
        }

        private static Double dbl(JsonObject o, String k) {
            JsonElement e = o.get(k);
            return e == null || e.isJsonNull() || !e.isJsonPrimitive() ? null : e.getAsDouble();
        }

        private static Boolean bool(JsonObject o, String k) {
            JsonElement e = o.get(k);
            return e == null || e.isJsonNull() || !e.isJsonPrimitive() ? null : e.getAsBoolean();
        }

        private static String raw(JsonObject o, String k) {
            JsonElement e = o.get(k);
            return e == null || e.isJsonNull() ? null : e.toString();
        }

        private List<String> strList(JsonObject o, String k) {
            List<String> l = strListOrNull(o, k);
            return l == null ? List.of() : l;
        }

        private List<String> strListOrNull(JsonObject o, String k) {
            if (!(o.get(k) instanceof JsonArray a)) return null;
            if (a.isEmpty()) return List.of();
            String[] out = new String[a.size()];
            int n = 0;
            for (JsonElement e : a) if (e.isJsonPrimitive()) out[n++] = intern(e.getAsString());
            return List.of(n == out.length ? out : Arrays.copyOf(out, n));
        }

        private static Stats stats(JsonElement el) {
            if (!(el instanceof JsonObject o)) return null;
            int hp = st(o, "hp"), at = st(o, "attack"), df = st(o, "defence"), sa = st(o, "special_attack"),
                sd = st(o, "special_defence"), sp = st(o, "speed");
            Integer total = integer(o, "total");
            boolean complete = hp >= 0 && at >= 0 && df >= 0 && sa >= 0 && sd >= 0 && sp >= 0;
            int t = total != null ? total : complete ? hp + at + df + sa + sd + sp : Stats.MISSING;
            return new Stats(hp, at, df, sa, sd, sp, t);
        }

        private static int st(JsonObject o, String k) {
            Integer v = integer(o, k);
            return v == null ? Stats.MISSING : v;
        }
